from datetime import timedelta
from typing import Dict, Any
from temporalio import workflow
from temporalio.common import RetryPolicy

# Import activity definitions for type-safe invocation
with workflow.unsafe.imports_passed_through():
    from activities.ci_activities import fetch_ci_failure_logs, generate_ci_repair_patches
    from activities.github_activities import inspect_repo_context, commit_code_patches
    from models.dtos import CIExecutionResult


@workflow.defn
class CIRepairWorkflow:
    @workflow.run
    async def run(
        self,
        run_id: int,
        head_branch: str,
        repo_name: str = "anonymousagar/epok",
        max_iterations: int = 3
    ) -> CIExecutionResult:
        retry_policy = RetryPolicy(
            initial_interval=timedelta(seconds=1),
            backoff_coefficient=2.0,
            maximum_interval=timedelta(seconds=30),
            maximum_attempts=3,
        )

        current_iteration = 0
        error_trace = ""

        while current_iteration < max_iterations:
            current_iteration += 1
            workflow.logger.info(f"Starting CI Self-Healing Repair Iteration {current_iteration}/{max_iterations} for branch {head_branch}...")

            # 1. Download workflow run failure logs
            log_result: Dict[str, Any] = await workflow.execute_activity(
                fetch_ci_failure_logs,
                args=[repo_name, run_id],
                start_to_close_timeout=timedelta(seconds=60),
                retry_policy=retry_policy,
            )

            error_trace = log_result.get("error_trace", "")

            # 2. Inspect repo context
            repo_context: Dict[str, Any] = await workflow.execute_activity(
                inspect_repo_context,
                args=[repo_name, head_branch],
                start_to_close_timeout=timedelta(seconds=60),
                retry_policy=retry_policy,
            )

            # 3. Generate Gemini repair code patches
            repaired_patches: Dict[str, str] = await workflow.execute_activity(
                generate_ci_repair_patches,
                args=[repo_name, head_branch, error_trace, repo_context.get("manifests", {})],
                start_to_close_timeout=timedelta(seconds=120),
                retry_policy=retry_policy,
            )

            if not repaired_patches:
                workflow.logger.warning("No repair patches generated by Gemini.")
                break

            # 4. Commit repaired code patches to PR branch
            commit_msg = f"fix(epok): automated CI repair attempt {current_iteration}/{max_iterations}"
            await workflow.execute_activity(
                commit_code_patches,
                args=[repo_name, head_branch, repaired_patches, commit_msg],
                start_to_close_timeout=timedelta(seconds=60),
                retry_policy=retry_policy,
            )

            workflow.logger.info(f"Pushed CI repair commit for iteration {current_iteration}.")

        return CIExecutionResult(
            success=False,  # Set to False until verified by next CI webhook run
            iteration=current_iteration,
            logs=error_trace,
            error_trace=error_trace,
        )

